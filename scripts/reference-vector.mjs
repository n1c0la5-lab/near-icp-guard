// Builds NEAR transactions with NEAR's own JS library (@near-js/transactions)
// and writes their bytes to canister/tests/vectors/near-tx.json.
//
// Why: the canister encodes transactions itself (Borsh). If our encoder and our
// tests share the same mistake, round-trip tests stay green while the network
// rejects every transaction. These vectors come from code we did not write.
//
// Usage: node reference-vector.mjs [output-path]

import { createHash } from "node:crypto";
import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import {
  actionCreators,
  createTransaction,
  encodeTransaction,
  SignedTransaction,
  Signature,
} from "@near-js/transactions";
import { PublicKey, KeyType, keyToImplicitAddress } from "@near-js/crypto";

const out = resolve(process.argv[2] ?? "../canister/tests/vectors/near-tx.json");

const hex = (b) => Buffer.from(b).toString("hex");
const bytes = (n, f) => Uint8Array.from({ length: n }, (_, i) => f(i));

function vector(name, { pk, signer, receiver, nonce, blockHash, yocto, sig }) {
  const publicKey = new PublicKey({ keyType: KeyType.ED25519, data: pk });
  const tx = createTransaction(
    signer,
    publicKey,
    receiver,
    nonce,
    [actionCreators.transfer(yocto)],
    blockHash,
  );
  const encoded = encodeTransaction(tx);
  const signed = new SignedTransaction({
    transaction: tx,
    signature: new Signature({ keyType: KeyType.ED25519, data: sig }),
  });
  return {
    name,
    public_key: hex(pk),
    signer_id: signer,
    receiver_id: receiver,
    nonce: nonce.toString(),
    block_hash: hex(blockHash),
    yocto: yocto.toString(),
    signature: hex(sig),
    tx: hex(encoded),
    tx_sha256: createHash("sha256").update(encoded).digest("hex"),
    signed_tx: hex(signed.encode()),
  };
}

const pk1 = bytes(32, (i) => i + 1);
const pk2 = bytes(32, (i) => 255 - i);

const cases = [
  vector("implicit-signer-one-near", {
    pk: pk1,
    // implicit account id = hex of the ed25519 public key, computed by NEAR's lib
    signer: keyToImplicitAddress(new PublicKey({ keyType: KeyType.ED25519, data: pk1 })),
    receiver: "bob.testnet",
    nonce: 123456789012n,
    blockHash: bytes(32, () => 0xaa),
    yocto: 10n ** 24n, // 1 NEAR, needs more than 64 bits
    sig: bytes(64, (i) => i),
  }),
  vector("named-signer-max-values", {
    pk: pk2,
    signer: "guard.testnet",
    receiver: "a-very-long-receiver-name.some-sub.testnet",
    nonce: 2n ** 64n - 1n, // u64::MAX
    blockHash: bytes(32, (i) => (i * 7) & 0xff),
    yocto: 2n ** 128n - 1n, // u128::MAX
    sig: bytes(64, (i) => 255 - i),
  }),
  vector("zero-transfer", {
    pk: pk1,
    signer: keyToImplicitAddress(new PublicKey({ keyType: KeyType.ED25519, data: pk1 })),
    receiver: "x.near",
    nonce: 0n,
    blockHash: bytes(32, () => 0),
    yocto: 0n,
    sig: bytes(64, () => 0),
  }),
];

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  JSON.stringify(
    {
      generator: "@near-js/transactions " +
        JSON.parse(readFileSync(new URL("./node_modules/@near-js/transactions/package.json", import.meta.url))).version,
      note: "Generated by scripts/reference-vector.mjs. Do not edit by hand.",
      cases,
    },
    null,
    2,
  ) + "\n",
);
console.log(`wrote ${cases.length} vectors to ${out}`);
