// Signs NEP-413 messages with NEAR's own JS library (near-api-js,
// `KeyPairSigner.signNep413Message`) and writes the results to
// canister/tests/vectors/nep413.json.
//
// The canister encodes NEP-413 payloads itself (tag + Borsh). The Rust test
// `canister/tests/nep413_vectors.rs` verifies each signature below over the
// hash *our* encoder computes: if our tag, field order or Option encoding
// differed from NEAR's library, no signature would verify.
//
// Keys are fixed test keys derived from constant seeds (Ed25519 signatures are
// deterministic), so the file only changes when the library's output changes.
//
// Usage: node nep413-vector.mjs [output-path]

import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { KeyPair, KeyPairSigner } from "near-api-js";
import bs58 from "bs58";

const out = resolve(process.argv[2] ?? "../canister/tests/vectors/nep413.json");
const hex = (b) => Buffer.from(b).toString("hex");
const bytes = (n, f) => Uint8Array.from({ length: n }, (_, i) => f(i));

// A test key from a 32-byte seed. near-api-js reads the first 32 bytes of the
// "extended" secret key as the seed and derives the public key itself.
const testKey = (seedByte) => KeyPair.fromString("ed25519:" + bs58.encode(bytes(64, (i) => (i < 32 ? seedByte : 0))));

async function vector(name, { seed, message, nonce, recipient, callbackUrl }) {
  const signer = new KeyPairSigner(testKey(seed));
  const signed = await signer.signNep413Message("signer.testnet", { message, nonce, recipient, callbackUrl });
  return {
    name,
    message,
    nonce: hex(nonce),
    recipient,
    callback_url: callbackUrl ?? null,
    public_key: hex(signed.publicKey.data),
    signature: hex(signed.signature),
  };
}

const cases = [
  await vector("no-callback", {
    seed: 1,
    message: "Sign in to login.example",
    nonce: bytes(32, (i) => i),
    recipient: "login.example",
    callbackUrl: undefined, // Borsh None
  }),
  await vector("with-callback", {
    seed: 2,
    message: '{"action":"login","ts":1762100000}',
    nonce: bytes(32, () => 0xff),
    recipient: "app.example",
    callbackUrl: "https://app.example/cb?state=1",
  }),
  await vector("empty-callback-is-some", {
    seed: 3,
    message: "Zahlung bestätigen — 0,1 NEAR ✓", // multi-byte UTF-8: lengths count bytes
    nonce: bytes(32, (i) => (i * 37 + 11) & 0xff),
    recipient: "a",
    callbackUrl: "", // Borsh Some(""), not None
  }),
  await vector("maximum-sizes", {
    seed: 4,
    message: "x".repeat(4096),
    nonce: bytes(32, () => 0),
    recipient: "r".repeat(128),
    callbackUrl: "https://" + "u".repeat(504),
  }),
];

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  JSON.stringify(
    {
      generator:
        "near-api-js " +
        JSON.parse(readFileSync(new URL("./node_modules/near-api-js/package.json", import.meta.url))).version +
        " KeyPairSigner.signNep413Message",
      note: "Generated by scripts/nep413-vector.mjs. Do not edit by hand.",
      cases,
    },
    null,
    2,
  ) + "\n",
);
console.log(`wrote ${cases.length} NEP-413 vectors to ${out}`);
